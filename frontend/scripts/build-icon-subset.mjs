// Builds the bundled Iconify subset used by components/icon.tsx.
//
// Kobi ships only the icons it actually renders. The full Lucide set is ~1,960 icons; bundling it
// would cost far more than the handful we use, and loading icons from Iconify's API at runtime
// would mean the browser calling a third party, which the frontend is not allowed to do.
//
// Run `npm run icons:build` after adding a name to ICONS below.

import { writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";
import { icons as lucide } from "@iconify-json/lucide";
import { getIcons } from "@iconify/utils";

/**
 * Every icon the UI renders, as Lucide names. Keep it alphabetical; the key is the name used in
 * `<Icon name="..." />`, so these are the catalogue's own names rather than invented aliases.
 */
const ICONS = [
  "archive",
  "arrow-down",
  "arrow-left",
  "arrow-right",
  "arrow-up",
  "arrow-up-right",
  "bell",
  "check",
  "chevron-down",
  "chevron-right",
  "circle-check",
  "code",
  "ellipsis",
  "file-text",
  "flame",
  "globe",
  "grip-vertical",
  "heading-1",
  "heading-2",
  "heading-3",
  "history",
  "info",
  "layout-grid",
  "list",
  "list-ordered",
  "lock",
  "message-square",
  "minus",
  "panel-left-close",
  "panel-left-open",
  "plus",
  "quote",
  "search",
  "sparkle",
  "sparkles",
  "square-check",
  "star",
  "target",
  "trash-2",
  "type",
  "users",
  "x",
];

const here = dirname(fileURLToPath(import.meta.url));
const componentsDir = join(here, "..", "components");

const subset = getIcons(lucide, ICONS);
if (!subset) {
  throw new Error("getIcons() returned nothing - is @iconify-json/lucide installed?");
}

// getIcons() resolves aliases into the icons it returns, so a name listed above that is an alias
// in the source set (currently "history") still has to come back as a usable icon.
const resolved = new Set([...Object.keys(subset.icons ?? {}), ...Object.keys(subset.aliases ?? {})]);
const missing = ICONS.filter((name) => !resolved.has(name));
if (missing.length > 0) {
  throw new Error(`Icons missing from the Lucide set: ${missing.join(", ")}`);
}

await writeFile(join(componentsDir, "icon-subset.json"), `${JSON.stringify(subset)}\n`, "utf8");

const names = [...ICONS].sort();
await writeFile(
  join(componentsDir, "icon-names.ts"),
  `// Generated by scripts/build-icon-subset.mjs. Do not edit by hand.
// Run \`npm run icons:build\` to regenerate.

export const ICON_NAMES = [
${names.map((name) => `  "${name}",`).join("\n")}
] as const;

export type IconName = (typeof ICON_NAMES)[number];
`,
  "utf8",
);

console.log(`icons: wrote ${names.length} icons to components/icon-subset.json`);
